-- The DMS side of the pipeline: warehouse, tables, stages, stream and merge task.
-- Variables: dms_wh, bucket, integration.
CREATE WAREHOUSE IF NOT EXISTS <% dms_wh %>
  WITH WAREHOUSE_SIZE = 'LARGE' WAREHOUSE_TYPE = 'STANDARD' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
-- Every tool's warehouse is Large with a 60 s auto-suspend, so their credits are comparable.
ALTER WAREHOUSE <% dms_wh %> SET WAREHOUSE_SIZE = 'LARGE' AUTO_SUSPEND = 60;

-- Explicit as well, so the DMS tables don't depend on the schema default.
CREATE TABLE DMS_FULL_LOAD (
  AID INT NOT NULL,
  BID INT,
  ABALANCE INT,
  FILLER VARCHAR,
  __FILENAME VARCHAR,
  __ROW_NUMBER INT,
  __SCAN_TIME TIMESTAMP_NTZ,
  __LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
) ROW_TIMESTAMP = TRUE;

CREATE TABLE DMS_HISTORY (
  AID INT NOT NULL,
  BID INT,
  ABALANCE INT,
  FILLER VARCHAR,
  OP VARCHAR,
  DMS_TIMESTAMP VARCHAR,
  __FILENAME VARCHAR,
  __ROW_NUMBER INT,
  __SCAN_TIME TIMESTAMP_NTZ,
  __LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
) ROW_TIMESTAMP = TRUE;

CREATE TABLE DMS_REPLICATION (
  AID INT NOT NULL,
  BID INT,
  ABALANCE INT,
  FILLER VARCHAR,
  __FILENAME VARCHAR,
  __ROW_NUMBER INT,
  __SCAN_TIME TIMESTAMP_NTZ,
  __LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
) ROW_TIMESTAMP = TRUE;

CREATE STAGE DMS_FULL_LOAD_STAGE
  URL = 's3://<% bucket %>/dms-full-load/'
  STORAGE_INTEGRATION = <% integration %>
  FILE_FORMAT = (TYPE = 'PARQUET');

CREATE STAGE DMS_CDC_STAGE
  URL = 's3://<% bucket %>/dms/'
  STORAGE_INTEGRATION = <% integration %>
  FILE_FORMAT = (TYPE = 'PARQUET');

CREATE STREAM DMS_HISTORY_STREAM ON TABLE DMS_HISTORY APPEND_ONLY = TRUE;

-- Created suspended. bench.sh resumes it for each CDC run.
CREATE TASK DMS_MERGE_TASK
  WAREHOUSE = <% dms_wh %>
  SCHEDULE = '1 minute'
WHEN
  SYSTEM$STREAM_HAS_DATA('DMS_HISTORY_STREAM')
AS
  MERGE INTO DMS_REPLICATION AS t
  USING (
    SELECT * FROM DMS_HISTORY_STREAM
    QUALIFY ROW_NUMBER() OVER (PARTITION BY AID ORDER BY FILLER DESC) = 1
  ) AS s
    ON t.AID = s.AID
  WHEN MATCHED AND s.OP = 'D' THEN DELETE
  WHEN MATCHED THEN
    UPDATE SET
      t.BID = s.BID,
      t.ABALANCE = s.ABALANCE,
      t.FILLER = s.FILLER,
      t.__FILENAME = s.__FILENAME,
      t.__ROW_NUMBER = s.__ROW_NUMBER,
      t.__SCAN_TIME = s.__SCAN_TIME,
      t.__LOADED_AT = s.__LOADED_AT
  WHEN NOT MATCHED THEN
    INSERT (AID, BID, ABALANCE, FILLER, __FILENAME, __ROW_NUMBER, __SCAN_TIME, __LOADED_AT)
    VALUES (s.AID, s.BID, s.ABALANCE, s.FILLER, s.__FILENAME, s.__ROW_NUMBER, s.__SCAN_TIME, s.__LOADED_AT);
