-- Every run of a merge task (DMS_MERGE_TASK or DEBEZIUM_MERGE_TASK) in a window, to see whether the merge keeps up
-- with its 1-minute schedule.
-- Variables: task, start, end (ISO 8601 UTC).
SELECT
  STATE,
  TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEDULED_TIME), 'YYYY-MM-DD"T"HH24:MI:SS"Z"') AS SCHEDULED_UTC,
  TO_CHAR(CONVERT_TIMEZONE('UTC', QUERY_START_TIME), 'YYYY-MM-DD"T"HH24:MI:SS"Z"') AS STARTED_UTC,
  TO_CHAR(CONVERT_TIMEZONE('UTC', COMPLETED_TIME), 'YYYY-MM-DD"T"HH24:MI:SS"Z"') AS COMPLETED_UTC,
  ROUND(DATEDIFF('millisecond', QUERY_START_TIME, COMPLETED_TIME) / 1000, 1) AS SECONDS,
  ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME => '<% task %>',
  SCHEDULED_TIME_RANGE_START => DATEADD('minute', -5, '<% start %>'::TIMESTAMP_LTZ),
  RESULT_LIMIT => 10000))
WHERE SCHEDULED_TIME <= '<% end %>'::TIMESTAMP_LTZ
ORDER BY SCHEDULED_TIME;
